def clean(v: Any) -> str:
    if v is None:
        return ""

    return re.sub(r"\s+", " ", str(v)).strip()


def norm(v: Any) -> str:
    text = clean(v)
    text = unicodedata.normalize("NFKD", text)
    text = "".join(ch for ch in text if not unicodedata.combining(ch))
    return re.sub(r"\s+", " ", text.casefold()).strip()


def normalize_attendance(v: Any) -> str:
    key = norm(v)
    if not key:
        return "blank"
    if key in YES_VALUES:
        return "yes"
    if key in NO_VALUES:
        return "no"
    return "other"


def connect_mysql(connection_string: str):
    p = urlparse(connection_string)
    if p.scheme not in {"mysql", "mysql+pymysql"}:
        raise ValueError("Connection string must begin mysql://")
    if not p.hostname or not p.username or not p.path.strip("/"):
        raise ValueError("Connection string is incomplete.")

    q = parse_qs(p.query)
    kwargs = {
        "host": p.hostname,
        "port": p.port or 3306,
        "user": unquote(p.username),
        "password": unquote(p.password or ""),
        "database": p.path.lstrip("/"),
        "charset": q.get("charset", ["utf8mb4"])[0],
        "autocommit": False,
        "cursorclass": pymysql.cursors.DictCursor,
        "connect_timeout": 15,
        "read_timeout": 60,
        "write_timeout": 60,
    }
    if q.get("ssl", ["false"])[0].lower() in {"1", "true", "yes"}:
        kwargs["ssl"] = {}

    conn = pymysql.connect(**kwargs)
    with conn.cursor() as cur:
        cur.execute("SET time_zone = '+00:00'")
    return conn


