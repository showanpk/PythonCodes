#!/usr/bin/env python3
"""
OCF CRM - Historical Monday Sessions + Attendance Migration (Phase 2)

PHASE 2 ONLY
------------
Creates/reuses:
  - sessions
  - session_registrations
  - attendance

It DOES NOT create/update:
  - participants
  - participant_activity_types
  - activity_types
  - activities

Those were handled in Phase 1.

SAFETY
------
- Preview is the default.
- Database writes happen only with --commit.
- Participant identity comes only from the prior preview CSV where
  match_status == MATCHED_NAME_DOB.
- Blank Monday cells create no registration/attendance.
- Yes -> Attended + Present
- No  -> NoShow + Absent
- Explicit Cancelled source columns -> Cancelled session, no attendance.
- Duplicate source session dates for the SAME canonical activity are deduplicated
  only when their matched attendance sets agree.
- Conflicting duplicate source dates are blocked for manual review.
- Existing CRM sessions on the same canonical activity/date are reused only when
  the exact start/end time matches. A different existing time on the same date
  is treated as a conflict.
- Missing historical session times block commit; times are never invented.

REQUIRED INPUTS
---------------
1) Folder containing the original 30 attendance Excel files.
2) Participant preview CSV generated by:
     preview_ocf_monday_activity_sessions.py
3) Session preview CSV generated by:
     preview_ocf_monday_activity_sessions.py
4) A JSON time configuration file.

TIME CONFIG
-----------
The time JSON uses programme + weekday rules. Example:

{
  "Girls Football": {
    "Tuesday": {"start": "17:00", "end": "18:00"},
    "Wednesday": {"start": "17:00", "end": "18:00"}
  }
}

Optional date-range overrides are supported:

{
  "Girls Football": {
    "default": {"start": "17:00", "end": "18:00"},
    "overrides": [
      {
        "from": "2026-01-01",
        "to": "2026-12-31",
        "weekday": "Wednesday",
        "start": "18:00",
        "end": "19:00"
      }
    ]
  }
}

Resolution order:
  1. matching date-range override
  2. exact weekday rule
  3. default rule

RUN PREVIEW
-----------
py -3.14 .\migrate_ocf_sessions_attendance.py `
  --source-dir ".\Session Excels" `
  --participants-csv ".\ocf_monday_activity_sessions_preview_20260913_213900_participants.csv" `
  --sessions-csv ".\ocf_monday_activity_sessions_preview_20260913_213900_sessions.csv" `
  --times ".\ocf_session_times.json"

RUN COMMIT
----------
Only after preview has 0 blocking session/time conflicts:

py -3.14 .\migrate_ocf_sessions_attendance.py `
  --source-dir ".\Session Excels" `
  --participants-csv ".\ocf_monday_activity_sessions_preview_20260913_213900_participants.csv" `
  --sessions-csv ".\ocf_monday_activity_sessions_preview_20260913_213900_sessions.csv" `
  --times ".\ocf_session_times.json" `
  --commit
"""

