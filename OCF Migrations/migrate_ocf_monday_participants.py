def parse_excel_date(
    value: Any,
    workbook_epoch: datetime,
    *,
    redacted_sample: bool = False,
) -> str | None:
    if value is None:
        return None

    if isinstance(value, datetime):
        return value.date().isoformat()

    if isinstance(value, date):
        return value.isoformat()

    if isinstance(value, (int, float)):
        # Excel serial date. Reasonable serial range avoids treating normal small integers as dates.
        if value < 1 or value > 100000:
            return None
        try:
            dt = from_excel(value, workbook_epoch)
            if isinstance(dt, datetime):
                return dt.date().isoformat()
            if isinstance(dt, date):
                return dt.isoformat()
        except Exception:
            return None

    text = clean_text(value, redacted_sample=redacted_sample)
    if not text:
        return None

    if " to " in text.casefold():
        return None

    for fmt in (
        "%Y-%m-%d",
        "%d/%m/%Y",
        "%d-%m-%Y",
        "%d.%m.%Y",
        "%m/%d/%Y",
        "%b %d, %Y",
        "%B %d, %Y",
    ):
        try:
            return datetime.strptime(text, fmt).date().isoformat()
        except ValueError:
            continue

    return None


def age_on(dob_iso: str, reference_iso: str | None) -> int:
    dob = date.fromisoformat(dob_iso)
    reference = date.fromisoformat(reference_iso) if reference_iso else date.today()
    years = reference.year - dob.year - ((reference.month, reference.day) < (dob.month, dob.day))
    return years


