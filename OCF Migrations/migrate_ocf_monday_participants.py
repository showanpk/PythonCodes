def audit_row(p: PreparedParticipant) -> dict[str, Any]:
    if p.duplicate_matches:
        result = "DUPLICATE_REVIEW"
    elif p.blockers:
        result = "BLOCKED_REVIEW"
    elif p.inserted_ocf_id:
        result = "INSERTED"
    else:
        result = "READY"

    duplicate_text = "; ".join(
        f"{m['ocfId']} ({','.join(m['matchedBy'])})"
        for m in p.duplicate_matches
    )

    return {
        "source_row": p.source_row,
        "batch": p.batch,
        "result": result,
        "full_name": p.full_name,
        "date_of_birth": p.date_of_birth or "",
        "age_at_form": p.age_at_form if p.age_at_form is not None else "",
        "gender": p.gender or "",
        "postcode": p.postcode or "",
        "mobile_source": p.mobile_source or "",
        "preview_ocf_id": p.preview_ocf_id or "",
        "inserted_ocf_id": p.inserted_ocf_id or "",
        "duplicate_matches": duplicate_text,
        "blockers": " | ".join(p.blockers),
        "warnings": " | ".join(p.warnings),
        "monday_status": p.source_status or "",
        "legacy_signature_url": p.signature_url or "",
        "unmapped_notes": p.notes_value or "",
        "unmapped_files": p.files_value or "",
        "consent_form_source": p.consent_form_value or "",
    }


def write_audit_csv(path: Path, rows: list[PreparedParticipant]) -> None:
    fieldnames = list(audit_row(rows[0]).keys()) if rows else [
        "source_row",
        "batch",
        "result",
    ]

    with path.open("w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for p in rows:
            writer.writerow(audit_row(p))


def summary_counts(rows: list[PreparedParticipant]) -> dict[str, int]:
    return {
        "source_rows": len(rows),
        "ready_or_inserted": sum(1 for p in rows if p.ready),
        "duplicates_review": sum(1 for p in rows if p.duplicate_matches),
        "blocked_review": sum(1 for p in rows if p.blockers and not p.duplicate_matches),
        "with_warnings": sum(1 for p in rows if p.warnings),
        "inserted": sum(1 for p in rows if p.inserted_ocf_id),
    }


def print_summary(
    source: Path,
    batch: str,
    rows: list[PreparedParticipant],
    audit_path: Path,
    committed: bool,
) -> None:
    counts = summary_counts(rows)

    print()
    print("OCF Monday Participant Migration")
    print("--------------------------------")
    print(f"Source:                         {source}")
    print(f"Batch:                          {batch}")
    print(f"Source participant rows:        {counts['source_rows']}")
    print(f"Ready / eligible:               {counts['ready_or_inserted']}")
    print(f"Possible duplicates (REVIEW):   {counts['duplicates_review']}")
    print(f"Blocked rows (REVIEW):          {counts['blocked_review']}")
    print(f"Rows with warnings:             {counts['with_warnings']}")
    if committed:
        print(f"Inserted:                       {counts['inserted']}")
    print(f"Audit CSV:                      {audit_path}")
    print()

    if committed:
        print("COMMIT COMPLETE: eligible participants were inserted.")
    else:
        print("PREVIEW COMPLETE: database was NOT changed.")
        print("Review the audit CSV, then rerun with --commit only when you are satisfied.")


