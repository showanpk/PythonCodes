def connect_mysql(connection_string: str) -> Connection:
    parsed = urlparse(connection_string)

    if parsed.scheme not in {"mysql", "mysql+pymysql"}:
        raise ValueError(
            "Connection string must start with mysql:// or mysql+pymysql://"
        )

    if not parsed.hostname or not parsed.username or not parsed.path.strip("/"):
        raise ValueError(
            "Connection string is incomplete. Expected mysql://USER:PASSWORD@HOST:3306/DATABASE"
        )

    query = parse_qs(parsed.query)
    charset = query.get("charset", ["utf8mb4"])[0]
    ssl_requested = query.get("ssl", ["false"])[0].casefold() in {"1", "true", "yes"}

    kwargs: dict[str, Any] = {
        "host": parsed.hostname,
        "port": parsed.port or 3306,
        "user": unquote(parsed.username),
        "password": unquote(parsed.password or ""),
        "database": parsed.path.lstrip("/"),
        "charset": charset,
        "autocommit": False,
        "cursorclass": pymysql.cursors.DictCursor,
        "connect_timeout": 15,
        "read_timeout": 60,
        "write_timeout": 60,
    }

    if ssl_requested:
        kwargs["ssl"] = {}

    conn = pymysql.connect(**kwargs)
    with conn.cursor() as cur:
        cur.execute("SET time_zone = '+00:00'")
    return conn


def check_schema(conn: Connection) -> None:
    required_tables = {
        "participants",
        "participant_id_sequences",
        "participant_guardians",
        "emergency_contacts",
        "participant_health",
        "participant_equality",
        "communication_preferences",
        "consent_records",
        "audit_logs",
    }

    with conn.cursor() as cur:
        cur.execute("SHOW TABLES")
        found = {next(iter(row.values())) for row in cur.fetchall()}

    missing = sorted(required_tables - found)
    if missing:
        raise RuntimeError(
            "Database is missing required OCF CRM tables: " + ", ".join(missing)
        )


def current_next_participant_number(conn: Connection) -> int:
    with conn.cursor() as cur:
        cur.execute(
            "SELECT next_number FROM participant_id_sequences "
            "WHERE sequence_name='participant' LIMIT 1"
        )
        row = cur.fetchone()
    if not row:
        raise RuntimeError("participant_id_sequences does not contain the participant sequence.")
    number = int(row["next_number"])
    if number < 1:
        raise RuntimeError("Participant sequence is invalid.")
    return number


def allocate_participant_number(conn: Connection) -> int:
    with conn.cursor() as cur:
        cur.execute(
            "SELECT next_number FROM participant_id_sequences "
            "WHERE sequence_name=%s FOR UPDATE",
            ("participant",),
        )
        row = cur.fetchone()
        if not row:
            raise RuntimeError("Participant ID sequence is not configured.")

        number = int(row["next_number"])
        if number < 1:
            raise RuntimeError("Participant ID sequence is invalid.")

        cur.execute(
            "UPDATE participant_id_sequences "
            "SET next_number=next_number+1 "
            "WHERE sequence_name=%s AND next_number=%s",
            ("participant", number),
        )
        if cur.rowcount != 1:
            raise RuntimeError("Participant ID sequence could not be advanced.")

    return number


def ocf_id(first_name: str, last_name: str, participant_number: int) -> str:
    first_initial = first_name.strip()[0].upper()
    last_initial = last_name.strip()[0].upper()

    if not first_initial.isalpha() or not last_initial.isalpha():
        raise ValueError("First and last names must each begin with a letter.")

    return f"OCF-{first_initial}{last_initial}-{participant_number:04d}"


def find_duplicates(
    conn: Connection,
    full_name: str,
    dob: str,
    mobile: str | None,
    guardian_phone: str | None,
) -> list[dict[str, Any]]:
    matches: dict[str, dict[str, Any]] = {}

    def add(rows: list[dict[str, Any]], matched_by: str) -> None:
        for row in rows:
            pid = str(row["id"])
            entry = matches.setdefault(
                pid,
                {
                    "id": pid,
                    "ocfId": row["ocf_id"],
                    "fullName": row["full_name"],
                    "dateOfBirth": str(row["date_of_birth"]),
                    "mobileNumber": row["mobile_number"],
                    "matchedBy": [],
                },
            )
            if matched_by not in entry["matchedBy"]:
                entry["matchedBy"].append(matched_by)

    with conn.cursor() as cur:
        cur.execute(
            """
            SELECT id,ocf_id,full_name,date_of_birth,mobile_number
            FROM participants
            WHERE LOWER(TRIM(full_name)) = LOWER(TRIM(%s))
              AND date_of_birth = %s
            LIMIT 20
            """,
            (full_name, dob),
        )
        add(cur.fetchall(), "name+dob")

        if mobile:
            cur.execute(
                """
                SELECT id,ocf_id,full_name,date_of_birth,mobile_number
                FROM participants
                WHERE mobile_number = %s
                  AND date_of_birth = %s
                LIMIT 20
                """,
                (mobile, dob),
            )
            add(cur.fetchall(), "mobile+dob")

        if guardian_phone:
            cur.execute(
                """
                SELECT DISTINCT p.id,p.ocf_id,p.full_name,p.date_of_birth,p.mobile_number
                FROM participants p
                INNER JOIN participant_guardians g ON g.participant_id=p.id
                WHERE g.phone_number=%s
                  AND p.date_of_birth=%s
                LIMIT 20
                """,
                (guardian_phone, dob),
            )
            add(cur.fetchall(), "guardian_phone+dob")

    return list(matches.values())


