def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Migrate Monday.com OCF participant Excel export into OCF CRM MySQL."
    )
    parser.add_argument(
        "--source",
        required=True,
        help="Path to Monday.com participant export .xlsx",
    )
    parser.add_argument(
        "--batch",
        required=True,
        choices=["girls", "boys", "mixed"],
        help="Source batch label only. It does NOT create separate CRM structures.",
    )
    parser.add_argument(
        "--connection-string",
        default=DEFAULT_CONNECTION_STRING,
        help=(
            "MySQL URL. Prefer OCF_MYSQL_CONNECTION_STRING environment variable. "
            "Example: mysql://user:password@host:3306/ocf_crm?charset=utf8mb4"
        ),
    )
    parser.add_argument(
        "--commit",
        action="store_true",
        help="Actually write READY rows. Without this flag the script is preview-only.",
    )
    parser.add_argument(
        "--allow-guardian-phone-for-adults",
        action="store_true",
        default=ALLOW_GUARDIAN_PHONE_FOR_18_PLUS_DEFAULT,
        help=(
            "Override: permit guardian mobile to populate participants.mobile_number "
            "for age 18+ / unknown age. Default is OFF."
        ),
    )
    parser.add_argument(
        "--redacted-sample",
        action="store_true",
        help=(
            "Use ONLY with the sample workbook where exact value '34' is a redaction placeholder. "
            "Do NOT use for the real export."
        ),
    )
    return parser.parse_args()


def validate_connection_string(value: str) -> None:
    if "YOUR_DB_" in value:
        raise RuntimeError(
            "Replace the placeholder connection string or set OCF_MYSQL_CONNECTION_STRING."
        )


def main() -> int:
    args = parse_args()

    source = Path(args.source).expanduser().resolve()
    if not source.exists():
        print(f"ERROR: Source file not found: {source}", file=sys.stderr)
        return 2

    if source.suffix.casefold() != ".xlsx":
        print("ERROR: Source must be an .xlsx file.", file=sys.stderr)
        return 2

    try:
        validate_connection_string(args.connection_string)
        conn = connect_mysql(args.connection_string)
    except Exception as exc:
        print(f"ERROR connecting to MySQL: {exc}", file=sys.stderr)
        return 3

    try:
        check_schema(conn)

        monday = MondaySheet(source, redacted_sample=args.redacted_sample)
        prepared: list[PreparedParticipant] = []

        for source_row, row in monday.participant_rows():
            p = prepare_row(
                monday,
                source_row,
                row,
                args.batch,
                args.allow_guardian_phone_for_adults,
            )
            prepared.append(p)

        # Duplicate checks happen even in PREVIEW.
        for p in prepared:
            if p.date_of_birth and p.full_name:
                p.duplicate_matches = find_duplicates(
                    conn,
                    p.full_name,
                    p.date_of_birth,
                    p.mobile_number,
                    p.guardian_phone,
                )

        # Preview OCF IDs are simulated from the current sequence.
        simulated_next = current_next_participant_number(conn)
        for p in prepared:
            if p.ready and p.first_name and p.last_name:
                try:
                    p.preview_ocf_id = ocf_id(
                        p.first_name,
                        p.last_name,
                        simulated_next,
                    )
                    simulated_next += 1
                except Exception as exc:
                    p.blockers.append(f"Could not generate OCF ID: {exc}")

        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        mode = "commit" if args.commit else "preview"
        audit_path = source.parent / (
            f"ocf_monday_{args.batch}_{mode}_{timestamp}.csv"
        )

        if args.commit:
            # Recheck everything inside one transaction.
            # Any unexpected DB exception rolls back the whole inserted batch.
            conn.begin()
            try:
                for p in prepared:
                    if p.blockers:
                        continue

                    p.duplicate_matches = find_duplicates(
                        conn,
                        p.full_name,
                        p.date_of_birth or "",
                        p.mobile_number,
                        p.guardian_phone,
                    )
                    if p.duplicate_matches:
                        continue

                    participant_id, generated_ocf_id = insert_participant(conn, p)
                    p.inserted_participant_id = participant_id
                    p.inserted_ocf_id = generated_ocf_id

                conn.commit()
            except Exception:
                conn.rollback()
                raise
        else:
            # Ensure preview remains read-only even if driver started a transaction.
            conn.rollback()

        write_audit_csv(audit_path, prepared)
        print_summary(source, args.batch, prepared, audit_path, args.commit)

        # Exit nonzero when review items exist, but only after producing the audit file.
        # This is useful in scripted runs and does not mean the script crashed.
        if any(p.blockers or p.duplicate_matches for p in prepared):
            return 10

        return 0

    except Exception as exc:
        try:
            conn.rollback()
        except Exception:
            pass
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    finally:
        conn.close()


if __name__ == "__main__":
    raise SystemExit(main())
