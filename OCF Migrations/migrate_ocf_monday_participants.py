#!/usr/bin/env python3
"""
OCF CRM - Monday.com Participant Migration (Excel -> MySQL)

Designed for the OCF CRM schema reviewed from the PHP/MySQL backend.

Safety:
- PREVIEW is the default. It does not write to the database.
- Use --commit only after reviewing the preview CSV/summary.
- Girls and Boys can be migrated as separate batches into the SAME OCF participant tables.
- Monday "Status" is NOT mapped to OCF registration_status.
- Existing/possible duplicate participants are skipped for review.
- Safeguarding concerns are never silently discarded: meaningful concerns block the row for review.
- Legacy signature URLs are not inserted into the signatures table because that table expects a
  private stored file + hash, not an external Monday.com URL.

Dependencies:
    py -m pip install openpyxl PyMySQL

Recommended connection setup (PowerShell):
    $env:OCF_MYSQL_CONNECTION_STRING="mysql://DB_USER:DB_PASSWORD@DB_HOST:3306/DB_NAME?charset=utf8mb4"

If the password contains @, :, /, #, ? or other URL special characters, URL-encode it.

Preview:
    python migrate_ocf_monday_participants.py --source "Girls.xlsx" --batch girls

Commit after reviewing preview:
    python migrate_ocf_monday_participants.py --source "Girls.xlsx" --batch girls --commit

For the redacted sample workbook only:
    python migrate_ocf_monday_participants.py --source "sample.xlsx" --batch girls --redacted-sample
"""

