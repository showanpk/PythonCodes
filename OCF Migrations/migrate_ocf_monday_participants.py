def clean_text(value: Any, *, redacted_sample: bool = False) -> str | None:
    if value is None:
        return None

    if isinstance(value, datetime):
        value = value.isoformat(sep=" ")

    text = re.sub(r"\s+", " ", str(value)).strip()
    if not text:
        return None

    if redacted_sample and text == SAMPLE_REDACTED_VALUE:
        return None

    return text


def normalize_name(value: Any, *, redacted_sample: bool = False) -> str | None:
    text = clean_text(value, redacted_sample=redacted_sample)
    if not text:
        return None
    return re.sub(r"\s+", " ", text).strip()


def split_participant_name(full_name: str) -> tuple[str | None, str | None]:
    """
    OCF ID requires first AND last initial.
    Do not invent a surname for single-name records.
    """
    parts = [p for p in re.split(r"\s+", full_name.strip()) if p]
    if len(parts) < 2:
        return None, None
    return parts[0], " ".join(parts[1:])


def normalize_gender(value: Any, *, redacted_sample: bool = False) -> str | None:
    text = clean_text(value, redacted_sample=redacted_sample)
    if not text:
        return None
    key = text.casefold()
    mapping = {
        "girl": "Female",
        "female": "Female",
        "woman": "Female",
        "boy": "Male",
        "male": "Male",
        "man": "Male",
        "non-binary": "Non-Binary",
        "nonbinary": "Non-Binary",
        "prefer not to say": "Prefer not to say",
    }
    return mapping.get(key, text)


def normalize_uk_mobile(value: Any, *, redacted_sample: bool = False) -> str | None:
    if value is None:
        return None

    # Excel may return phone numbers as numeric cells.
    # Avoid values such as 7712345678.0.
    if isinstance(value, float):
        if value.is_integer():
            text = str(int(value))
        else:
            text = str(value)
    elif isinstance(value, int):
        text = str(value)
    else:
        text = clean_text(value, redacted_sample=redacted_sample)

    if not text:
        return None

    # Remove normal phone formatting.
    compact = re.sub(r"[\s().\-]", "", text)

    # 07712345678
    if re.fullmatch(r"07\d{9}", compact):
        return "+44" + compact[1:]

    # Excel has removed the leading zero:
    # 7712345678
    if re.fullmatch(r"7\d{9}", compact):
        return "+44" + compact

    # +447712345678
    if re.fullmatch(r"\+447\d{9}", compact):
        return compact

    # 447712345678
    if re.fullmatch(r"447\d{9}", compact):
        return "+" + compact

    # 00447712345678
    if re.fullmatch(r"00447\d{9}", compact):
        return "+" + compact[2:]

    # Handles +44(0)7712345678
    if re.fullmatch(r"\+4407\d{9}", compact):
        return "+44" + compact[4:]

    return None


def normalize_email(value: Any, *, redacted_sample: bool = False) -> str | None:
    text = clean_text(value, redacted_sample=redacted_sample)
    if not text:
        return None

    # Deliberately conservative. Bad emails are preserved as warnings rather than invented/fixed.
    if re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", text):
        return text

    return None


def normalize_postcode(value: str) -> str:
    compact = re.sub(r"\s+", "", value.upper())
    return compact[:-3] + " " + compact[-3:]


def extract_address_postcode(
    value: Any,
    *,
    redacted_sample: bool = False,
) -> tuple[str | None, str | None]:
    text = clean_text(value, redacted_sample=redacted_sample)
    if not text:
        return None, None

    matches = list(UK_POSTCODE_RE.finditer(text))
    if not matches:
        return text, None

    match = matches[-1]
    postcode = normalize_postcode(match.group(1))
    address = (text[: match.start()] + " " + text[match.end() :]).strip(" ,;-")
    address = re.sub(r"\s+", " ", address).strip()
    return address or None, postcode


def parse_yes_no(value: Any, *, redacted_sample: bool = False) -> bool | None:
    text = clean_text(value, redacted_sample=redacted_sample)
    if text is None:
        return None

    key = text.casefold().strip()
    if key in YES_TEXT:
        return True
    if key in NO_TEXT:
        return False
    return None


def health_value(
    value: Any,
    *,
    redacted_sample: bool = False,
) -> tuple[bool | None, str | None]:
    text = clean_text(value, redacted_sample=redacted_sample)
    if not text:
        return None, None

    key = text.casefold().strip()
    if key in NEGATIVE_TEXT:
        return False, None

    yes_no = parse_yes_no(text, redacted_sample=redacted_sample)
    if yes_no is False:
        return False, None
    if yes_no is True:
        # "Yes" with no details: keep flag true, details unavailable.
        return True, None

    return True, text


def parse_communication_preferences(
    value: Any,
    *,
    redacted_sample: bool = False,
) -> dict[str, bool] | None:
    text = clean_text(value, redacted_sample=redacted_sample)
    if not text:
        return None

    lower = text.casefold()

    prefs = {
        "email": False,
        "sms": False,
        "phone": False,
        "whatsapp": False,
        "post": False,
        "do_not_contact": False,
    }

    if any(token in lower for token in ("do not contact", "no contact", "none")):
        prefs["do_not_contact"] = True
        return prefs

    prefs["email"] = "email" in lower
    prefs["sms"] = "text" in lower or "sms" in lower
    prefs["phone"] = "phone" in lower or "call" in lower
    prefs["whatsapp"] = "whatsapp" in lower
    prefs["post"] = bool(re.search(r"\bpost\b", lower))

    return prefs


def parse_gdpr(value: Any, *, redacted_sample: bool = False) -> tuple[bool | None, bool | None]:
    text = clean_text(value, redacted_sample=redacted_sample)
    if not text:
        return None, None

    lower = text.casefold()

    if lower in NO_TEXT:
        return False, False

    gdpr = None
    anon = None

    if "processing of my personal data" in lower or "process my personal data" in lower:
        gdpr = True

    if "anonymised data" in lower or "anonymized data" in lower:
        anon = True

    return gdpr, anon


def meaningful_safeguarding_concern(value: Any, *, redacted_sample: bool = False) -> str | None:
    text = clean_text(value, redacted_sample=redacted_sample)
    if not text:
        return None

    if text.casefold() in NEGATIVE_TEXT:
        return None

    parsed = parse_yes_no(text, redacted_sample=redacted_sample)
    if parsed is False:
        return None

    return text


