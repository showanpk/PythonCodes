def choose_photo_consent(
    values: list[Any],
    *,
    redacted_sample: bool = False,
) -> tuple[bool | None, str | None]:
    parsed: list[bool] = []
    for value in values:
        answer = parse_yes_no(value, redacted_sample=redacted_sample)
        if answer is not None:
            parsed.append(answer)

    if not parsed:
        return None, None

    if len(set(parsed)) > 1:
        return None, "Conflicting Photo/Video Consent values in duplicated Monday columns."

    return parsed[0], None


def prepare_row(
    sheet: MondaySheet,
    source_row: int,
    row: tuple[Any, ...],
    batch: str,
    allow_guardian_phone_for_adults: bool,
) -> PreparedParticipant:
    redacted = sheet.redacted_sample
    out = PreparedParticipant(source_row=source_row, batch=batch)

    out.full_name = normalize_name(
        sheet.value(row, "Name"),
        redacted_sample=redacted,
    ) or ""

    if not out.full_name:
        out.blockers.append("Missing participant name.")
    else:
        first, last = split_participant_name(out.full_name)
        if not first or not last:
            out.blockers.append(
                "Cannot safely split participant name into first name + last name; OCF ID requires both."
            )
        else:
            out.first_name = first
            out.last_name = last

    out.date_of_birth = parse_excel_date(
        sheet.value(row, "Date of Birth"),
        sheet.epoch,
        redacted_sample=redacted,
    )
    if not out.date_of_birth:
        out.blockers.append("Missing or invalid Date of Birth.")

    out.date_form_completed = parse_excel_date(
        sheet.value(row, "Date Form Completed"),
        sheet.epoch,
        redacted_sample=redacted,
    )
    if not out.date_form_completed:
        out.warnings.append("Date Form Completed is missing/invalid; migration date will be used for created_at.")

    if out.date_of_birth:
        try:
            out.age_at_form = age_on(out.date_of_birth, out.date_form_completed)
        except Exception:
            out.age_at_form = None

    out.gender = normalize_gender(
        sheet.value(row, "Gender"),
        redacted_sample=redacted,
    )

    if batch.casefold() == "girls" and out.gender == "Male":
        out.warnings.append("Row is in Girls batch but source Gender is Male.")
    if batch.casefold() == "boys" and out.gender == "Female":
        out.warnings.append("Row is in Boys batch but source Gender is Female.")

    out.source_status = clean_text(
        sheet.value(row, "Status"),
        redacted_sample=redacted,
    )
    out.school_name = clean_text(
        sheet.value(row, "School Name"),
        redacted_sample=redacted,
    )

    out.home_address, out.postcode = extract_address_postcode(
        sheet.value(row, "Home Address and Postcode"),
        redacted_sample=redacted,
    )
    if not out.postcode:
        out.blockers.append("Could not extract a valid UK postcode from Home Address and Postcode.")

    out.guardian_name = normalize_name(
        sheet.value(row, "Parent/Guardian Name"),
        redacted_sample=redacted,
    )
    raw_guardian_phone = sheet.value(row, "Parent/Guardian Phone Number")
    out.guardian_phone = normalize_uk_mobile(
        raw_guardian_phone,
        redacted_sample=redacted,
    )
    guardian_phone_text = clean_text(raw_guardian_phone, redacted_sample=redacted)
    if guardian_phone_text and not out.guardian_phone:
        out.warnings.append("Parent/Guardian Phone Number is present but is not a valid UK mobile.")

    raw_guardian_email = sheet.value(row, "Parent/Guardian Email Address")
    out.guardian_email = normalize_email(
        raw_guardian_email,
        redacted_sample=redacted,
    )
    guardian_email_text = clean_text(raw_guardian_email, redacted_sample=redacted)
    if guardian_email_text and not out.guardian_email:
        out.warnings.append("Parent/Guardian Email Address is present but invalid.")

    out.emergency_name = normalize_name(
        sheet.value(row, "Emergency Contact Name"),
        redacted_sample=redacted,
    )
    out.emergency_relationship = clean_text(
        sheet.value(row, "Relationship to the Participant"),
        redacted_sample=redacted,
    )
    raw_emergency_phone = sheet.value(row, "Emergency Contact Phone Number")
    out.emergency_phone = normalize_uk_mobile(
        raw_emergency_phone,
        redacted_sample=redacted,
    )
    emergency_phone_text = clean_text(raw_emergency_phone, redacted_sample=redacted)
    if emergency_phone_text and not out.emergency_phone:
        out.warnings.append("Emergency Contact Phone Number is present but is not a valid UK mobile.")

    out.emergency_pickup_authorised = parse_yes_no(
        sheet.value(row, "Is this person authorised to pick up the participant?"),
        redacted_sample=redacted,
    )

    # Monday source has no participant mobile column.
    # Safe fallback: primary guardian mobile for under-18.
    if out.age_at_form is not None and out.age_at_form < 18:
        out.guardian_relationship = "Parent/Guardian"
        if not out.guardian_name:
            out.blockers.append("Under-18 participant has no Parent/Guardian Name.")
        if not out.guardian_phone:
            out.blockers.append("Under-18 participant has no valid Parent/Guardian mobile.")
        if out.guardian_phone:
            out.mobile_number = out.guardian_phone
            out.mobile_source = "guardian"
    else:
        if allow_guardian_phone_for_adults and out.guardian_phone:
            out.mobile_number = out.guardian_phone
            out.mobile_source = "guardian_adult_override"
            out.warnings.append(
                "Adult/unknown-age participant mobile populated from guardian phone because override was enabled."
            )
        else:
            out.blockers.append(
                "No participant mobile exists in Monday export. For age 18+ / unknown age, manual review is required."
            )

    # Emergency contact safety rule.
    emergency_complete = bool(
        out.emergency_name
        and out.emergency_relationship
        and out.emergency_phone
    )
    if out.age_at_form is not None and out.age_at_form < 18:
        if not emergency_complete:
            out.blockers.append(
                "Under-18 participant does not have a complete emergency contact (name, relationship, valid mobile)."
            )
    elif any((out.emergency_name, out.emergency_relationship, out.emergency_phone)) and not emergency_complete:
        out.warnings.append("Emergency contact is incomplete and will not be inserted.")

    # Health.
    has_medical, medical = health_value(
        sheet.value(row, "Medical Condition"),
        redacted_sample=redacted,
    )
    has_dietary, dietary = health_value(
        sheet.value(row, "Dietary Needs/Allergies"),
        redacted_sample=redacted,
    )
    takes_medication, medication = health_value(
        sheet.value(row, "Are you currently taking any medication?"),
        redacted_sample=redacted,
    )
    has_disability, disability = health_value(
        sheet.value(row, "Disability"),
        redacted_sample=redacted,
    )
    gp_details = clean_text(
        sheet.value(row, "Doctor’s Name and Contact Number (GP):"),
        redacted_sample=redacted,
    )

    out.health = {
        "has_medical_condition": has_medical,
        "medical_condition": medical,
        "has_dietary_needs_allergies": has_dietary,
        "dietary_needs_allergies": dietary,
        "takes_medication": takes_medication,
        "medication": medication,
        "has_disability": has_disability,
        "disability": disability,
        "gp_details": gp_details,
    }

    out.ethnic_origin = clean_text(
        sheet.value(row, "Ethnic Origin"),
        redacted_sample=redacted,
    )
    out.religion = clean_text(
        sheet.value(row, "Religion"),
        redacted_sample=redacted,
    )

    out.communication = parse_communication_preferences(
        sheet.value(row, "Consent for Communication:"),
        redacted_sample=redacted,
    )

    out.photo_video_consent, photo_error = choose_photo_consent(
        sheet.values(row, "Photo/Video Consent"),
        redacted_sample=redacted,
    )
    if photo_error:
        out.blockers.append(photo_error)

    out.gdpr_personal_data_consent, out.anonymised_reporting_consent = parse_gdpr(
        sheet.value(row, "GDPR and Data Protection"),
        redacted_sample=redacted,
    )

    safeguarding = meaningful_safeguarding_concern(
        sheet.value(row, "Safeguarding Concerns"),
        redacted_sample=redacted,
    )
    if safeguarding:
        out.blockers.append(
            "Safeguarding Concerns contains meaningful data but current OCF schema has no safe mapped destination. Review manually before migration."
        )

    out.signature_url = clean_text(
        sheet.value(row, "Signature"),
        redacted_sample=redacted,
    )
    if out.signature_url:
        out.warnings.append(
            "Legacy signature URL found. It will NOT be inserted into signatures because OCF signatures require a private stored file + hash."
        )

    out.consent_form_value = clean_text(
        sheet.value(row, "Consent Form"),
        redacted_sample=redacted,
    )
    if out.consent_form_value:
        out.warnings.append("Consent Form source value/file is not mapped; retained in local migration audit only.")

    out.notes_value = clean_text(
        sheet.value(row, "Notes"),
        redacted_sample=redacted,
    )
    if out.notes_value:
        out.warnings.append("Monday Notes are not mapped to a current participant column; retained in local migration audit only.")

    out.files_value = clean_text(
        sheet.value(row, "Files"),
        redacted_sample=redacted,
    )
    if out.files_value:
        out.warnings.append("Monday Files are not mapped to a current participant column; retained in local migration audit only.")

    # Do NOT map Monday Status to registration_status.
    if out.source_status:
        out.warnings.append(
            f"Monday Status '{out.source_status}' preserved only as migration metadata; not mapped to OCF registration_status."
        )

    return out


