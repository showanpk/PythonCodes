class MondaySheet:
    def __init__(self, path: Path, redacted_sample: bool = False):
        self.path = path
        self.redacted_sample = redacted_sample
        self.workbook = load_workbook(path, data_only=True, read_only=True)
        self.sheet = self.workbook.active
        self.epoch = self.workbook.epoch
        self.header_row_index, self.headers = self._find_header_row()
        self.header_positions = self._header_positions()

    def _find_header_row(self) -> tuple[int, list[str]]:
        for row_index, row in enumerate(self.sheet.iter_rows(values_only=True), start=1):
            values = [clean_text(v) or "" for v in row]
            if "Name" in values and "Date of Birth" in values and "Gender" in values:
                return row_index, values
        raise RuntimeError(
            "Could not find the Monday.com header row. Expected at least Name, Gender and Date of Birth."
        )

    def _header_positions(self) -> dict[str, list[int]]:
        positions: dict[str, list[int]] = {}
        for index, header in enumerate(self.headers):
            header = header.strip()
            if not header:
                continue
            positions.setdefault(header, []).append(index)
        return positions

    def value(self, row: tuple[Any, ...], header: str, occurrence: int = 0) -> Any:
        indexes = self.header_positions.get(header, [])
        if occurrence >= len(indexes):
            return None
        idx = indexes[occurrence]
        return row[idx] if idx < len(row) else None

    def values(self, row: tuple[Any, ...], header: str) -> list[Any]:
        out = []
        for idx in self.header_positions.get(header, []):
            out.append(row[idx] if idx < len(row) else None)
        return out

    def participant_rows(self) -> Iterable[tuple[int, tuple[Any, ...]]]:
        for row_index, row in enumerate(self.sheet.iter_rows(values_only=True), start=1):
            if row_index <= self.header_row_index:
                continue

            name_raw = self.value(row, "Name")
            name = clean_text(name_raw)

            # Skip genuinely empty rows and the Monday summary/range row in the sample export.
            if not name:
                continue
            if name == SAMPLE_REDACTED_VALUE:
                continue

            dob_raw = self.value(row, "Date of Birth")
            dob_text = clean_text(dob_raw)
            if dob_text and " to " in dob_text.casefold():
                continue

            yield row_index, row


