def insert_consent(
    conn: Connection,
    participant_id: str,
    consent_type: str,
    granted: bool | None,
    given_by: str | None,
    given_at: str | None,
) -> None:
    if granted is None:
        return

    status = "Granted" if granted else "Declined"
    given_datetime = (
        datetime.combine(date.fromisoformat(given_at), time(hour=12))
        if given_at
        else datetime.utcnow()
    )

    with conn.cursor() as cur:
        cur.execute(
            """
            INSERT INTO consent_records
            (id,participant_id,consent_type,status,given_by_name,given_at,wording_version,metadata_json)
            VALUES (%s,%s,%s,%s,%s,%s,%s,%s)
            """,
            (
                str(uuid.uuid4()),
                participant_id,
                consent_type,
                status,
                given_by,
                given_datetime,
                "LEGACY_MONDAY_EXPORT",
                json.dumps({"migration": MIGRATION_NAME}),
            ),
        )


def insert_participant(
    conn: Connection,
    p: PreparedParticipant,
) -> tuple[str, str]:
    if not p.ready:
        raise RuntimeError("Attempted to insert a participant that is not ready.")

    participant_id = str(uuid.uuid4())
    participant_number = allocate_participant_number(conn)
    generated_ocf_id = ocf_id(p.first_name, p.last_name, participant_number)

    historical_created_at = (
        datetime.combine(date.fromisoformat(p.date_form_completed), time(hour=12))
        if p.date_form_completed
        else datetime.utcnow()
    )

    with conn.cursor() as cur:
        cur.execute(
            """
            INSERT INTO participants
            (
                id,participant_number,ocf_id,
                registration_type,registration_status,registration_source,
                first_name,last_name,full_name,date_of_birth,
                mobile_number,email_address,postcode,gender,school_name,home_address,
                can_walk_home,date_form_completed,created_by,updated_by,
                created_at,updated_at
            )
            VALUES
            (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,NULL,%s,%s,%s,%s,NULL,%s,NULL,NULL,%s,NOW())
            """,
            (
                participant_id,
                participant_number,
                generated_ocf_id,
                REGISTRATION_TYPE,
                REGISTRATION_STATUS,
                REGISTRATION_SOURCE,
                p.first_name,
                p.last_name,
                p.full_name,
                p.date_of_birth,
                p.mobile_number,
                p.postcode,
                p.gender,
                p.school_name,
                p.home_address,
                p.date_form_completed,
                historical_created_at,
            ),
        )

        guardian_id: str | None = None
        if p.guardian_name and p.guardian_phone:
            guardian_id = str(uuid.uuid4())
            cur.execute(
                """
                INSERT INTO participant_guardians
                (id,participant_id,full_name,relationship,phone_number,email_address,is_primary)
                VALUES (%s,%s,%s,%s,%s,%s,1)
                """,
                (
                    guardian_id,
                    participant_id,
                    p.guardian_name,
                    p.guardian_relationship,
                    p.guardian_phone,
                    p.guardian_email,
                ),
            )

        if p.emergency_name and p.emergency_relationship and p.emergency_phone:
            linked_guardian_id = None
            if (
                guardian_id
                and p.guardian_name
                and p.emergency_name.casefold().strip() == p.guardian_name.casefold().strip()
            ):
                linked_guardian_id = guardian_id

            cur.execute(
                """
                INSERT INTO emergency_contacts
                (id,participant_id,full_name,relationship,phone_number,is_pickup_authorised,linked_guardian_id)
                VALUES (%s,%s,%s,%s,%s,%s,%s)
                """,
                (
                    str(uuid.uuid4()),
                    participant_id,
                    p.emergency_name,
                    p.emergency_relationship,
                    p.emergency_phone,
                    1 if p.emergency_pickup_authorised else 0,
                    linked_guardian_id,
                ),
            )

        if any(v is not None for v in p.health.values()):
            cur.execute(
                """
                INSERT INTO participant_health
                (
                    participant_id,
                    has_medical_condition,medical_condition,
                    has_dietary_needs_allergies,dietary_needs_allergies,
                    takes_medication,medication,
                    has_disability,disability,
                    gp_details
                )
                VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)
                """,
                (
                    participant_id,
                    p.health.get("has_medical_condition"),
                    p.health.get("medical_condition"),
                    p.health.get("has_dietary_needs_allergies"),
                    p.health.get("dietary_needs_allergies"),
                    p.health.get("takes_medication"),
                    p.health.get("medication"),
                    p.health.get("has_disability"),
                    p.health.get("disability"),
                    p.health.get("gp_details"),
                ),
            )

        if p.ethnic_origin is not None or p.religion is not None:
            cur.execute(
                """
                INSERT INTO participant_equality
                (participant_id,ethnic_origin,religion)
                VALUES (%s,%s,%s)
                """,
                (participant_id, p.ethnic_origin, p.religion),
            )

        if p.communication is not None:
            cur.execute(
                """
                INSERT INTO communication_preferences
                (participant_id,email,sms,phone,whatsapp,post,do_not_contact)
                VALUES (%s,%s,%s,%s,%s,%s,%s)
                """,
                (
                    participant_id,
                    int(p.communication["email"]),
                    int(p.communication["sms"]),
                    int(p.communication["phone"]),
                    int(p.communication["whatsapp"]),
                    int(p.communication["post"]),
                    int(p.communication["do_not_contact"]),
                ),
            )

    consent_given_by = p.guardian_name if (p.age_at_form is not None and p.age_at_form < 18) else p.full_name

    insert_consent(
        conn,
        participant_id,
        "PhotoVideo",
        p.photo_video_consent,
        consent_given_by,
        p.date_form_completed,
    )
    insert_consent(
        conn,
        participant_id,
        "GdprPersonalData",
        p.gdpr_personal_data_consent,
        consent_given_by,
        p.date_form_completed,
    )
    insert_consent(
        conn,
        participant_id,
        "AnonymisedReporting",
        p.anonymised_reporting_consent,
        consent_given_by,
        p.date_form_completed,
    )

    with conn.cursor() as cur:
        cur.execute(
            """
            INSERT INTO audit_logs
            (user_id,participant_id,action,entity_type,entity_id,ip_address,user_agent,metadata_json)
            VALUES (NULL,%s,%s,'Participant',%s,NULL,%s,%s)
            """,
            (
                participant_id,
                AUDIT_ACTION,
                participant_id,
                "python-monday-migration",
                json.dumps(
                    {
                        "migration": MIGRATION_NAME,
                        "batch": p.batch,
                        "sourceRow": p.source_row,
                        "sourceStatus": p.source_status,
                        "mobileSource": p.mobile_source,
                        "legacySignatureUrlPresent": bool(p.signature_url),
                        "warnings": p.warnings,
                    },
                    ensure_ascii=False,
                ),
            ),
        )

    return participant_id, generated_ocf_id


